interface I18nState {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
}

export const useI18n = create<I18nState>((set, get) => ({
  lang: "en",
  setLang: (l) => {
    if (typeof window !== "undefined") {
      localStorage.setItem("shetbhav_lang", l);
    }
    set({ lang: l });
  },
  t: (key) => {
    const { lang } = get();
    return translations[lang]?.[key] || translations.en[key] || key;
  },
}));

